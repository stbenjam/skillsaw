def test_tab_block_flattened_with_fence_and_blank_line():
    # docs/getting-started.md shape: fence and blank line inside a tab body.
    text = (
        '=== "macOS"\n'
        "\n"
        "    Install it:\n"
        "\n"
        "    ```bash\n"
        "    brew install skillsaw\n"
        "    ```\n"
        "\n"
        "After.\n"
    )
    result = site_content._plain_markdown(text)
    assert result == (
        "**macOS:**\n"
        "\n"
        "Install it:\n"
        "\n"
        "```bash\n"
        "brew install skillsaw\n"
        "```\n"
        "\n"
        "After.\n"
    )


def test_back_to_back_tabs():
    # A tab body ending directly at the next `=== ` marker line.
    text = '=== "pip"\n\n    pip install skillsaw\n=== "uv"\n\n    uvx skillsaw\n'
    result = site_content._plain_markdown(text)
    assert result == "**pip:**\n\npip install skillsaw\n**uv:**\n\nuvx skillsaw\n"


def test_admonition_with_table_and_icons():
    # docs/getting-started.md shape: admonition body holding a table with
    # icon shortcodes and attr lists; em dash in the title.
    text = (
        '!!! tip "Skip the manual setup — let the agent do it"\n'
        "\n"
        "    | What | Why |\n"
        "    |------|-----|\n"
        "    | :material-numeric-1-circle:{ .step-icon } | **Install** |\n"
    )
    result = site_content._plain_markdown(text)
    assert result == (
        "**Tip: Skip the manual setup — let the agent do it**\n"
        "\n"
        "| What | Why |\n"
        "|------|-----|\n"
        "| 1. | **Install** |\n"
    )


def test_bare_admonition_with_immediate_body():
    # docs/configuration.md shape: bare `!!! note`, body on the next line
    # with no blank line between.
    text = "!!! note\n    Plugin rule options work the same way.\nAfter.\n"
    result = site_content._plain_markdown(text)
    assert result == "**Note**\nPlugin rule options work the same way.\nAfter.\n"


def test_collapsible_admonition_flattened():
    # No `???` blocks exist in the corpus today; synthetic coverage for the
    # collapsible branch of the marker regex.
    text = '??? note "Details"\n    body\n'
    assert site_content._plain_markdown(text) == "**Note: Details**\nbody\n"


def test_list_indented_fence_content_preserved():
    # CommonMark allows fences indented 1-3 spaces (docs/plugins.md shape);
    # icon-like tokens inside them must not be stripped.
    text = '- item:\n\n  ```python\n  RULES = {":sparkles:"}\n  ```\n'
    assert site_content._plain_markdown(text) == text


def test_deprecated_page_admonition_multi_paragraph():
    # Generated rule-page shape: titled admonition, immediate body, and a
    # second indented paragraph after a blank line.
    text = (
        '!!! warning "Deprecated"\n'
        "    Deprecated since v0.16.0 and will be removed.\n"
        "\n"
        "    Use `agentskill-valid` instead.\n"
    )
    result = site_content._plain_markdown(text)
    assert result == (
        "**Warning: Deprecated**\n"
        "Deprecated since v0.16.0 and will be removed.\n"
        "\n"
        "Use `agentskill-valid` instead.\n"
    )


def test_plain_content_untouched_and_header_dropped():
    text = (
        "<!-- Generated by scripts/generate-site-content.py — do not edit by hand -->\n"
        "\n"
        "# Title\n"
        "\n"
        "<!-- skillsaw-disable content-weak-language -->\n"
        "\n"
        "    indented code block :sparkles: untouched\n"
        "\n"
        "Prose stays.\n"
    )
    result = site_content._plain_markdown(text)
    assert "Generated by scripts/generate-site-content" not in result
    assert "<!-- skillsaw-disable content-weak-language -->" in result
    assert "    indented code block :sparkles: untouched" in result
    assert "Prose stays." in result
    # Idempotent on already-plain text.
    assert site_content._plain_markdown(result) == result


def test_fence_state_tracking_with_nested_unclosed_fence():
    # docs/rules/content-unclosed-fence.md shape: a 4-backtick fence wrapping
    # an unclosed 3-backtick fence. Markers and icons inside are preserved;
    # a marker after the outer fence closes must still flatten.
    text = (
        "````markdown\n"
        "```bash\n"
        "echo unclosed\n"
        '=== "not a tab"\n'
        "````\n"
        "!!! note\n"
        "    body\n"
        "Then :sparkles: prose.\n"
    )
    result = site_content._plain_markdown(text)
    assert '=== "not a tab"' in result
    assert "**Note**" in result
    assert "body" in result
    assert ":sparkles:" not in result.split("````")[-1]


