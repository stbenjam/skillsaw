def test_numeric_icons_become_numbers_and_headings_collapse():
    # :material-numeric-N-circle: carries the step number — keep it as "N.";
    # icon removal must not leave doubled spaces in headings.
    text = "## :sparkles: Onboard with AI\n"
    assert site_content._plain_markdown(text) == "## Onboard with AI\n"


def test_inpage_hrule_rewritten_to_asterisks():
    # A `---` after a blank line is a horizontal rule: rewritten to `***` so
    # `---` stays reserved for llms-full page joins. A `---` directly under
    # text is a setext heading underline and must stay untouched.
    hrule = "Some prose.\n\n---\n\nMore prose.\n"
    assert site_content._plain_markdown(hrule) == "Some prose.\n\n***\n\nMore prose.\n"
    setext = "A Heading\n---\nBody.\n"
    assert site_content._plain_markdown(setext) == setext


def test_llms_txt_marks_deprecated_and_mentions_full_file(llms_txt):
    assert "https://skillsaw.org/llms-full.txt" in llms_txt
    assert "(deprecated since v" in llms_txt
    # Group blurbs carry a flattened first sentence, not bare counts alone.
    assert re.search(r"- \[Security\]\([^)]+\): \d+ rules — ", llms_txt)


def test_write_llms_outputs_writes_both_files(tmp_path):
    # The main() wiring: both endpoint files are produced, non-empty.
    import shutil

    docs_copy = tmp_path / "docs"
    shutil.copytree(DOCS_DIR, docs_copy)
    for name in ("llms.txt", "llms-full.txt"):
        (docs_copy / name).unlink(missing_ok=True)

    site_content.write_llms_outputs(docs_copy, site_content.collect_rules())

    assert (docs_copy / "llms.txt").stat().st_size > 1_000
    assert (docs_copy / "llms-full.txt").stat().st_size > 50_000


def test_only_bare_delimiters_close_fences():
    # CommonMark: a closing fence has no info string. A ```bash line inside
    # an open fence is content — markers after it must stay untouched.
    text = (
        "```markdown\n" "```bash\n" "echo hi\n" "!!! note\n" "    body\n" "```\n" "After prose.\n"
    )
    result = site_content._plain_markdown(text)
    assert "!!! note" in result
    assert "**Note**" not in result


def test_inline_code_spans_preserved_by_noise_strip():
    # Literal Material tokens documented in inline code survive; the same
    # tokens in surrounding prose are stripped.
    line = "Use `:sparkles:` or `{ .step-icon }` markers :sparkles: here.\n"
    result = site_content._plain_markdown(line)
    assert "`:sparkles:`" in result
    assert "`{ .step-icon }`" in result
    assert result.count(":sparkles:") == 1


def test_multi_backtick_span_with_inner_backtick_preserved():
    # CommonMark: a span closes at a run of exactly the opener's length, so
    # ``literal ` and :sparkles:`` is one span — nothing inside is stripped.
    line = "Use ``literal ` and :sparkles:`` but strip :sparkles: here.\n"
    result = site_content._plain_markdown(line)
    assert "``literal ` and :sparkles:``" in result
    assert result.count(":sparkles:") == 1
    # An unmatched backtick run stays plain text and its trailing prose is
    # still stripped.
    assert site_content._plain_markdown("open `` here :brain: x\n") == "open `` here x\n"
