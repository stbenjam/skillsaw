def test_guides_cover_the_real_docs_tree():
    assert site_content.guides_coverage_errors(DOCS_DIR) == []


def test_guides_coverage_flags_unlisted_page(tmp_path):
    docs = tmp_path / "docs"
    docs.mkdir()
    for _, relpath, _ in site_content.GUIDES:
        (docs / relpath).write_text("# stub\n", encoding="utf-8")
    (docs / "scratch.md").write_text("# stray\n", encoding="utf-8")
    errors = site_content.guides_coverage_errors(docs)
    assert len(errors) == 1
    assert "docs/scratch.md" in errors[0]
    assert "NON_GUIDE_DOCS" in errors[0]


def test_guides_coverage_flags_missing_page(tmp_path):
    docs = tmp_path / "docs"
    docs.mkdir()
    for _, relpath, _ in site_content.GUIDES:
        (docs / relpath).write_text("# stub\n", encoding="utf-8")
    (docs / site_content.GUIDES[1][1]).unlink()
    errors = site_content.guides_coverage_errors(docs)
    assert len(errors) == 1
    assert "does not exist" in errors[0]
    assert site_content.GUIDES[1][1] in errors[0]


