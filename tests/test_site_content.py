def llms_full():
    return site_content.generate_llms_full(DOCS_DIR)


def test_llms_txt_structure(llms_txt, rules_data):
    assert llms_txt.startswith("# skillsaw\n")
    assert "## Docs" in llms_txt
    assert "## Rules" in llms_txt
    assert "## Optional" in llms_txt
    assert (
        "https://raw.githubusercontent.com/stbenjam/skillsaw/main/docs/getting-started.md"
        in llms_txt
    )


def test_llms_txt_lists_every_canonical_rule_once(llms_txt, rules_data):
    urls = re.findall(r"\((https://raw\.githubusercontent\.com/[^)]+)\)", llms_txt)
    assert len(urls) == len(set(urls)), "duplicate URL in llms.txt"
    for rule_id in rules_data:
        assert "/docs/rules/{}.md".format(rule_id) in llms_txt


def test_llms_full_is_plain_markdown(llms_full):
    assert not re.search(r"^(=== |!!! |\?\?\?)", llms_full, re.MULTILINE)
    # Exact header text: a guide legitimately quotes an unrelated
    # "<!-- Generated by APM CLI ... -->" comment in inline code.
    assert "Generated by scripts/generate-site-content" not in llms_full
    assert "asciinema.org" not in llms_full
    assert "hide:" not in llms_full
    assert "{ .md-button" not in llms_full
    assert '<div class="grid' not in llms_full


def test_llms_full_covers_guides_and_rules(llms_full):
    # Assert each guide's own H1 as a heading line — nav titles are weak
    # evidence (most appear as substrings in other pages' prose).
    for _, relpath, _ in site_content.GUIDES:
        if relpath == "index.md":
            continue
        page = (DOCS_DIR / relpath).read_text(encoding="utf-8")
        h1 = re.search(r"^# (.+)$", page, re.MULTILINE)
        assert h1 is not None, "guide {} has no H1".format(relpath)
        assert re.search(
            r"^# {}$".format(re.escape(h1.group(1))), llms_full, re.MULTILINE
        ), "guide {} missing from llms-full".format(relpath)
    assert llms_full.count("\n# context-budget\n") == 1
    assert len(llms_full.encode("utf-8")) > 50_000


