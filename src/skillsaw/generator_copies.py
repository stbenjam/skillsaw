"""Conservative copy recognition over typed, contained source/output nodes.

This recognizes two released serializations; it is not a compiler. A mismatch
leaves the output fully lintable. Source paths are retained, not invented line
maps or a claim that a consumer interprets source and output equivalently.
"""

from __future__ import annotations

import re
from pathlib import Path

from skillsaw.blocks import (
    AgentsMdBlock,
    ClaudeMdBlock,
    CursorRuleBlock,
    PluginRuleBlock,
    FrontmatterField,
)
from skillsaw.blocks.generators import RulerRuleBlock, RulesyncConfigBlock, RulesyncRuleBlock
from skillsaw.formats.generators import RULESYNC_CONFIG, RULESYNC_RULE, schema_problems
from skillsaw.generated import GeneratedCopy
from skillsaw.paths import contained_resolve, relative_to_str
from skillsaw.utils import read_text


def _ruler_copy(node, sources, root, resolve):
    if not isinstance(node, (AgentsMdBlock, ClaudeMdBlock)):
        return None
    if node.resolved_path != node.path:
        return None
    raw = read_text(node.path)
    if not raw or "<!-- Source: " not in raw:
        return None
    base = node.path.parent
    prefix = "<!-- Generated by Ruler -->\n" if isinstance(node, AgentsMdBlock) else ""
    if not raw.startswith(prefix):
        return None
    offset, next_line = len(prefix), prefix.count("\n") + 3
    paths = []
    for comment in node.markdown.html_comments():
        # Literal comments inside a verified source body are authored content,
        # even when they use Ruler's boundary spelling. Consume whole sections.
        if comment.file_line_start < next_line:
            continue
        if comment.file_line_start != next_line:
            return None
        text = comment.text
        if not text.startswith(" Source: ") or not text.endswith(" "):
            return None
        name = text[len(" Source: ") : -1]
        # Only conventional local sources. Neither absolute paths nor a marker
        # escaping to a sibling or a developer's home can confer ownership.
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts or "\\" in name:
            return None
        source = sources.get(base / relative)
        if source is None or relative.parts[0] != ".ruler" or source.path in paths:
            return None
        if contained_resolve(source.path, root, resolve) is None:
            return None
        body = source.read_body(strip_code_blocks=False)
        if body is None:
            return None
        section = f"\n\n<!-- Source: {name} -->\n\n{body.strip()}\n"
        if not raw.startswith(section, offset):
            return None
        paths.append(source.path)
        offset += len(section)
        next_line += section.count("\n")
        if offset == len(raw):
            return GeneratedCopy("ruler", tuple(paths))
        if raw[offset] != "\n":
            return None
        offset += 1  # Ruler joins sections with one more newline.
        next_line += 1
    return None


def _rulesync_targets(project, nodes):
    if project.config is None:
        return ()
    config = nodes.get(project.config)
    if not isinstance(config, RulesyncConfigBlock) or config.parse_error:
        return ()
    data = config.raw_data
    if data is None or schema_problems(data, RULESYNC_CONFIG):
        return ()
    # Overrides, overlays, custom roots and per-target options have more than
    # one possible producer. They are linted, but this recognizer stands down.
    if (
        (project.root / "rulesync.local.jsonc").exists()
        or (project.root / ".rulesync.local").exists()
        or data.get("global", False)
        or "inputRoot" in data
        or "inputRoots" in data
        or data.get("outputRoots", ["."]) != ["."]
    ):
        return ()
    targets = data.get("targets", ["agentsmd"])
    features = data.get("features", ["rules"])
    if not isinstance(targets, list) or not isinstance(features, list):
        return ()
    if not {"rules", "*"}.intersection(features):
        return ()
    return tuple(t for t in ("claudecode", "cursor") if t in targets or "*" in targets)


def _rulesync_copy(source, target, output):
    # A symlink is another view of authored or consumer-owned data. Copy
    # attribution must never transfer to that file through a resolved index.
    if output.resolved_path != output.path:
        return False
    fm = source.raw_data
    if (
        source.frontmatter_error
        or not source.portable_keys
        or fm is None
        or schema_problems(fm, RULESYNC_RULE)
    ):
        return False
    if fm.get("root", False) or fm.get("localRoot", False):
        return False
    if not {target, "*"}.intersection(fm.get("targets", ["*"])):
        return False
    if output.frontmatter_error:
        return False
    # Metadata is compared semantically; copied prose is compared verbatim
    # after the generator's documented outer-whitespace trim.
    body = source.body_text.strip()
    if not body or output.body_text.strip() != body:
        return False
    if target == "claudecode":
        paths = fm.get("claudecode", {}).get("paths", fm.get("globs") or None)
        expected = {"paths": paths} if paths is not None else {}
    else:
        cursor = fm.get("cursor", {})
        expected = {}
        if "alwaysApply" in cursor:
            expected["alwaysApply"] = cursor["alwaysApply"]
        description = re.sub(r"\n+", " ", fm.get("description", "")).strip()
        if description:
            expected["description"] = description
        globs = cursor.get("globs", fm.get("globs", []))
        if globs and not (
            cursor.get("alwaysApply") is True and all(g.strip() in {"*", "**/*"} for g in globs)
        ):
            expected["globs"] = re.sub(r"[\r\n\u0085\u2028\u2029]+", " ", ",".join(globs)).strip()
    return {f.name: f.value for f in output.find(FrontmatterField)} == expected


def tag_generator_copies(context, tree):
    """Keep output nodes and all their consumer roles; annotate proven copies."""
    projects = context.generator_projects()
    if not projects:
        return
    nodes = {n.path: n for n in tree.walk() if n.parent is None or n.path != n.parent.path}
    sources = {n.path: n for n in tree.find(RulerRuleBlock)}
    for node in (*tree.find(AgentsMdBlock), *tree.find(ClaudeMdBlock)):
        if not node.content_suppressed:
            node.generated_copy = _ruler_copy(
                node, sources, context.root_path, context.resolve_path
            )
    if not context.rulesync_generated:
        return
    rules = {n.path: n for n in tree.find(RulesyncRuleBlock)}
    consumers = {
        "cursor": {n.path: n for n in tree.find(CursorRuleBlock)},
        "claudecode": {n.path: n for n in tree.find(PluginRuleBlock)},
    }
    for project in projects:
        if project.generator != "rulesync":
            continue
        targets = _rulesync_targets(project, nodes)
        for path in project.rules:
            source = rules.get(path)
            if source is None:
                continue
            relative = relative_to_str(path, project.source_dir)
            if relative is None:
                continue
            for target in targets:
                if target == "cursor":
                    destination = (
                        project.root / ".cursor/rules" / Path(relative).with_suffix(".mdc")
                    )
                else:
                    destination = project.root / ".claude/rules" / relative
                output = consumers[target].get(destination)
                if (
                    output is not None
                    and not output.content_suppressed
                    and _rulesync_copy(source, target, output)
                ):
                    output.generated_copy = GeneratedCopy("rulesync", (path,))
